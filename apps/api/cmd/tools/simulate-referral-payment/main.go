package main

import (
	"context"
	"flag"
	"fmt"
	"log"
	"strings"
	"time"

	"github.com/gilabs/gims/api/internal/core/apptime"
	"github.com/gilabs/gims/api/internal/core/infrastructure/config"
	"github.com/gilabs/gims/api/internal/core/infrastructure/database"
	"github.com/gilabs/gims/api/internal/core/logger"
	refModels "github.com/gilabs/gims/api/internal/referral/data/models"
	refRepos "github.com/gilabs/gims/api/internal/referral/data/repositories"
	refUC "github.com/gilabs/gims/api/internal/referral/domain/usecase"
	tenantModels "github.com/gilabs/gims/api/internal/tenant/data/models"
	userModels "github.com/gilabs/gims/api/internal/user/data/models"
)

func main() {
	var tenantID string
	var email string
	var amountIDR int64
	var subscriptionID string
	var invoiceID string

	flag.StringVar(&tenantID, "tenant-id", "", "tenant ID that already has a referral conversion")
	flag.StringVar(&email, "email", "", "tenant owner/user email; used to resolve tenant ID")
	flag.Int64Var(&amountIDR, "amount", 100000, "paid net amount in IDR")
	flag.StringVar(&subscriptionID, "subscription-id", "", "optional subscription ID; defaults to tenant active/trial subscription if found")
	flag.StringVar(&invoiceID, "invoice-id", "", "optional provider invoice ID; defaults to dev-referral-<timestamp>")
	flag.Parse()

	logger.Init()
	if err := config.Load(); err != nil {
		log.Fatal("load config: ", err)
	}
	if err := database.Connect(); err != nil {
		log.Fatal("connect database: ", err)
	}
	defer database.Close()

	ctx := context.Background()
	if amountIDR <= 0 {
		log.Fatal("amount must be greater than 0")
	}

	tenantID = strings.TrimSpace(tenantID)
	email = strings.ToLower(strings.TrimSpace(email))
	if tenantID == "" && email != "" {
		var user userModels.User
		if err := database.DB.WithContext(ctx).Where("lower(email) = ? AND deleted_at IS NULL", email).First(&user).Error; err != nil {
			log.Fatalf("resolve tenant by email %q: %v", email, err)
		}
		tenantID = user.TenantID
	}
	if tenantID == "" {
		log.Fatal("provide --tenant-id or --email")
	}

	var conversion refModels.SalesReferralConversion
	if err := database.DB.WithContext(ctx).Where("tenant_id = ? AND deleted_at IS NULL", tenantID).First(&conversion).Error; err != nil {
		log.Fatalf("tenant %s has no referral conversion; register with referral code first: %v", tenantID, err)
	}

	if subscriptionID == "" {
		var sub tenantModels.TenantSubscription
		if err := database.DB.WithContext(ctx).
			Where("tenant_id = ? AND deleted_at IS NULL", tenantID).
			Order("CASE WHEN status IN ('active','trial') THEN 0 ELSE 1 END, created_at DESC").
			First(&sub).Error; err == nil {
			subscriptionID = sub.ID
		}
	}

	if invoiceID == "" {
		invoiceID = fmt.Sprintf("dev-referral-%d", time.Now().UnixNano())
	}
	now := apptime.Now()
	txn := &tenantModels.PaymentTransaction{
		TenantID:          tenantID,
		SubscriptionID:    subscriptionID,
		Provider:          tenantModels.PaymentProviderInternal,
		Status:            tenantModels.PaymentStatusPaid,
		PaymentMethod:     tenantModels.PaymentMethodCoupon,
		AmountIDR:         amountIDR,
		ProviderInvoiceID: invoiceID,
		ProviderPaymentID: invoiceID,
		Description:       "DEV simulated paid discount coupon payment for referral commission",
		PaidAt:            &now,
		Notes:             "Generated by cmd/tools/simulate-referral-payment",
	}
	if err := database.DB.WithContext(ctx).Create(txn).Error; err != nil {
		log.Fatal("create payment transaction: ", err)
	}

	uc := refUC.NewReferralUsecase(refRepos.NewReferralRepository(database.DB), nil)
	if err := uc.CreateCommissionForPayment(ctx, txn.ID); err != nil {
		log.Fatal("create referral commission: ", err)
	}

	var commission refModels.ReferralCommission
	if err := database.DB.WithContext(ctx).Where("payment_transaction_id = ?", txn.ID).First(&commission).Error; err != nil {
		log.Fatal("fetch created commission: ", err)
	}

	fmt.Println("Simulated paid referral payment created")
	fmt.Printf("tenant_id=%s\n", tenantID)
	fmt.Printf("payment_transaction_id=%s\n", txn.ID)
	fmt.Printf("commission_id=%s\n", commission.ID)
	fmt.Printf("commission_type=%s\n", commission.CommissionType)
	fmt.Printf("source_net_amount_idr=%d\n", commission.SourceNetAmountIDR)
	fmt.Printf("commission_bps=%d\n", commission.CommissionBps)
	fmt.Printf("commission_amount_idr=%d\n", commission.CommissionAmountIDR)
	fmt.Printf("status=%s\n", commission.Status)
}
