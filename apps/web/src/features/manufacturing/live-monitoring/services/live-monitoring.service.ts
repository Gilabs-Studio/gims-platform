export async function fetchLiveMonitoringData(lineId: string = "all"): Promise<LiveMonitoringData> {
  // Simulates network call
  if (lineId === "all") {
    return MOCK_LIVE_MONITORING_DATA;
  }

  // Filtered line dataset simulation
  const line = MOCK_LIVE_MONITORING_DATA.lineStatuses.find((l) => l.id === lineId);
  return {
    ...MOCK_LIVE_MONITORING_DATA,
    lineStatuses: line ? [line] : MOCK_LIVE_MONITORING_DATA.lineStatuses,
  };
}
